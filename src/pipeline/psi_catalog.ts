export function getPsiMetadata(id: string): EnrichedPsiInvestigation | undefined {
  return PSI_CATALOG[id];
}

export function isCombustionInvestigation(id: string): boolean {
  const item = PSI_CATALOG[id];
  return item ? item.isCombustion : false;
}

export function getInvestigationsByCategory(category: InvestigationCategory): EnrichedPsiInvestigation[] {
  return Object.values(PSI_CATALOG).filter(p => p.category === category);
}

export function getInvestigationsByFacility(facility: string): EnrichedPsiInvestigation[] {
  return Object.values(PSI_CATALOG).filter(p => p.facility === facility);
}
